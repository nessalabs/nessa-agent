#!/usr/bin/env node
/**
 * MCP Apps over a real gateway (#384): a real MCP server's app, drawn in the
 * desktop window of a browser preview (`desktop.html?gateway`), its calls
 * going through a real gateway to the real server.
 *
 * It starts, each of its own and on 127.0.0.1:
 * - a gateway in a temporary `ci` namespace, with the test MCP server
 *   (`scripts/mcp-test-server/server.mjs`) as `mcptest` and one agent's runtime
 *   (`--agent claude|codex`, default claude)
 *   (`scripts/mcp-test-server/local-gateway.mjs`, as `live-check.mjs` does);
 * - a dev server whose `/browser` proxy is that gateway.
 *
 * It asks the agent, through `NessaClient`, to call the server's app tool
 * (`review_rows`) once, and allows that call alone; an agent that calls it
 * more than once leaves the run "could not run". Then, in each engine, it
 * signs the page in with the gateway's owner token through `/browser/login`
 * from the page, opens the conversation, and checks the review app the
 * server serves. Shown inline, the app calls the server's destructive tool
 * and two tools hidden from apps as soon as it has its tool result.
 *
 * With `--scripted`, the gateway runs `scripts/mcp-test-server/scripted-agent.mjs`
 * as the agent's runtime instead of its harness: no model, no sign-in. It
 * calls `review_rows` for real and reports the call in the frames the harness
 * was recorded sending, so the gateway's projection of one call's several
 * updates reaches the window the same way every run (#418).
 *
 * Otherwise it uses the agent's own sign-in on this machine and creates no account. The
 * owner token is generated by the gateway it provisions, read from the
 * gateway's temporary directory, never printed, and removed with it.
 *
 * Every step runs on one page per engine, in order; a step that fails stops
 * those after it, which are reported as not run — except `hidden`, which
 * leaves nothing waiting.
 */
