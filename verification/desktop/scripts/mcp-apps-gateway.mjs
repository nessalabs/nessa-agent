/** The gateway, the dev server in front of it, and a conversation in which the agent called the app tool. */
async function startStack(options) {
  if (options.mode === "prod") throw new CannotRun("not run: dev server only")
  const stack = await startGatewayStack({ ...options, mode: "dev" }, "mcp-apps-gateway", {
    scripted: options.scripted ? APP_TOOL : undefined,
    evidence: options.scripted ? options.evidence : undefined,
  })
  try {
    const started = Date.now()
    const conversationId = randomUUID()
    const turn = await appToolTurn(stack.client, conversationId, options.agent)
    if (options.evidence) writeView(options.evidence, "view.json", turn.view)
    stack.timings.agentTurnMs = Date.now() - started
    const { conversations } = await stack.client.conversation.list({})
    const title = conversations.find(
      (each) => each.conversationId === conversationId,
    )?.title
    log(
      `conversation ready: ${APP_TOOL} ${turn.tool.status}, in ${stack.timings.agentTurnMs} ms`,
    )
    // Registered by the stack, which imported this client first.
    const { mcpAppCallTiming } = await import("@nessa/client")
    return {
      ...stack,
      conversationId,
      title,
      reviewWaitMs: appReviewWaitMs(mcpAppCallTiming),
    }
  } catch (error) {
    await stack.close()
    throw error
  }
}

/**
 * Asks `agent` to call the app tool once, answers the permission requests
 * of one call of it (`admitOnce`), and waits
 * for the turn to end (`agentTurn`). A gateway with no sign-in for the agent
 * refuses the conversation, and an agent that calls the app tool more than
 * once leaves the steps nothing unambiguous to read: both are "could not run".
 */
async function appToolTurn(client, conversationId, agent) {
  const once = (calls) =>
    new CannotRun(
      `${agent} called ${APP_TOOL} more than once (${calls}); the check admits exactly one call`,
    )
  // The one call of the app tool allowed, and the permissions answered for it.
  let admitted = null
  const answered = new Set()
  const { view, turn: last } = await agentTurn(
    client,
    conversationId,
    toolPrompt([{ name: APP_TOOL }]),
    {
      agent,
      create: true,
      seconds: 300,
      // Only the permission requests of one call of the app tool are
      // answered; any other request stays unanswered.
      onView: async (view) => {
        for (;;) {
          const { allow, extra } = admitOnce(view, admitted, answered, SERVER, APP_TOOL)
          if (extra) throw once(`${admitted}, ${extra}`)
          if (!allow) break
          admitted = allow.call
          answered.add(permissionKey(allow.permission))
          await client.conversation.answer(
            conversationId,
            allow.permission.executionId,
            allow.permission.permissionId,
            allow.option.id,
          )
        }
      },
    },
  )
  const outcome = setupOutcome(view, SERVER, APP_TOOL)
  if (outcome.kind === "repeated") throw once(outcome.calls.map(callKey).join(", "))
  const tool = outcome.call
  if (outcome.kind !== "ready")
    throw new CannotRun(
      `${agent}'s turn ended ${last.status}${last.error ? ` (${last.error.code ?? last.error})` : ""}; ` +
        `${APP_TOOL}: ${tool ? `${tool.status}, resourceUri ${tool.mcp.resourceUri ?? "none"}` : "not called"}; ` +
        `the view's tools: ${JSON.stringify(view.tools.map(({ title, status, mcp }) => ({ title, status, mcp })))}; ` +
        `its reply: ${JSON.stringify(
          last.parts
            .filter((part) => part.kind === "text")
            .map((part) => part.text)
            .join("")
            .slice(0, 400),
        )}`,
    )
  return { view, tool }
}

/** The app's pending reviews in the conversation, as the gateway's view says. */
async function appReviews(client, conversationId) {
  const view = await client.conversation.read(conversationId)
  return appPermissions(view)
}

/** What an output of the review app says, once it says anything but `pending`. */
async function output(frame, id, timeout = 10_000) {
  const selector = css.reviewOutput(id)
  await frame
    .waitForFunction(
      (selector) => {
        const text = document.querySelector(selector)?.textContent ?? ""
        return text !== "" && text !== "pending"
      },
      selector,
      { timeout },
    )
    .catch(() => {})
  return frame.evaluate(
    (selector) => document.querySelector(selector)?.textContent ?? "",
    selector,
  )
}

const said = (frame, id) =>
  frame.evaluate(
    (selector) => document.querySelector(selector)?.textContent ?? "",
    css.reviewOutput(id),
  )

/** The keys of the app's reviews pending now: a baseline taken before an action. */
const pendingReviews = async (stack) =>
  reviewKeys(await appReviews(stack.client, stack.conversationId))

/**
 * Waits up to `ms` for an app review not in `baseline`: the one the action
 * opened. `windowOpened` uses the time it has left, so a fast run reaches
 * the steps with the review already listed. A review that takes longer is
 * the step's own wait (`awaitReview`), which does not stop at this bound.
 */
const reviewOpened = (stack, baseline, ms = appReviewUnstartedMs) =>
  waitFor(
    async () => newReview(await appReviews(stack.client, stack.conversationId), baseline),
    ms,
  )

/**
 * The step's wait for the review its own call opened (#474). While the
 * app's output for that call is still pending, a review the gateway lists
 * later is that review; the call ending with none is reported as answered;
 * neither by `stack.reviewWaitMs` — the client's call deadline — is absent.
 * An output that never becomes pending stops at `appReviewUnstartedMs`:
 * no call is in flight, so the absence is not a late review.
 */
const awaitReview = (stack, baseline, pending) =>
  waitForAppReview({
    read: () => stack.client.conversation.read(stack.conversationId),
    baseline,
    deadlineMs: stack.reviewWaitMs,
    pending,
    sleep,
  })

/** Lines of the gateway log that bear on an app call, for a wait that found no review. */
function gatewayExcerpt(stack) {
  const text = stack.gateway?.log?.() ?? ""
  const lines = text
    .split("\n")
    .filter((line) =>
      /app_delete_row|ApprovalRequested|temporarily_unavailable|mcp_cancelled|Withdrawn|call_tool|callTool/i.test(
        line,
      ),
    )
    .slice(-20)
  const chosen = lines.length > 0 ? lines : text.split("\n").filter(Boolean).slice(-8)
  if (chosen.length === 0) return ""
  return `gateway log: ${chosen.join(" | ").slice(-1500)}`
}

/** Waits up to `ms` for `review` to be pending no longer; whether it went. */
const reviewGone = (stack, review, ms) =>
  waitFor(
    async () =>
      !stillPending(await appReviews(stack.client, stack.conversationId), review),
    ms,
  )

/** Waits up to `ms` for `review` to be the conversation's first pending permission: the one the window shows. */
const reviewShown = (stack, review, ms = 10_000) =>
  waitFor(async () => {
    const view = await stack.client.conversation.read(stack.conversationId)
    const first = view.permissions[0]
    return first !== undefined && permissionKey(first) === permissionKey(review)
  }, ms)

/**
 * Denies, in the window, each of the app's reviews pending now, oldest first,
 * so the window's card is free for the review a step's own action opens
 * (deny's, release's).
 * Returns the keys of what is still pending: the step's baseline.
 */
async function settleEarlier(page, stack, failures) {
  for (const review of await appReviews(stack.client, stack.conversationId)) {
    if (!(await reviewShown(stack, review))) {
      failures.push("an earlier review of the app's is not the window's approval")
      break
    }
    const card = await approvalShown(page, SERVER, DESTRUCTIVE)
    if (!card) {
      failures.push(`the window shows no approval naming ${DESTRUCTIVE}`)
      break
    }
    const deny = offeredLabel(review.options, "deny")
    if (!deny) {
      failures.push("an earlier review offers no deny")
      break
    }
    await card.getByRole("button", { name: deny, exact: true }).click()
    if (!(await reviewGone(stack, review, 10_000)))
      failures.push("an earlier review of the app's is still pending after Deny")
  }
  return pendingReviews(stack)
}

/**
 * Waits for the app's review of a destructive call in the gateway's view and
 * in the window, answers it in the window with the option of `effect`, and
 * returns what was seen. The button is that option's own label (#444).
 * `baseline` is the app's reviews pending before the call was made, so the
 * call's own is told apart from any left from before. `pending` reads
 * what the app shows for the call, so a call that ends with no review is
 * told apart from one whose review has not been listed yet (#474).
 */
async function reviewAndAnswer(page, stack, baseline, effect, failures, pending) {
  const waited = await awaitReview(stack, baseline, pending)
  if (waited.kind === "answered") {
    failures.push(
      `the call was answered without a review in the conversation's permissions: "${waited.output}"`,
    )
    return null
  }
  if (waited.kind !== "review") {
    failures.push(reviewAbsentMessage(waited.samples, waited.reads))
    const excerpt = gatewayExcerpt(stack)
    if (excerpt) failures.push(excerpt)
    return null
  }
  const review = waited.review
  const seen = {
    arrivedMs: waited.samples.at(-1)?.ms ?? null,
    toolName: review.toolName,
    origin: review.origin,
    argumentsJson: review.argumentsJson,
    options: review.options.map((each) => each.effect),
  }
  if (
    review.origin.kind !== "app" ||
    review.origin.server !== SERVER ||
    review.origin.tool !== DESTRUCTIVE
  )
    failures.push(`the review's origin is ${JSON.stringify(review.origin)}`)
  // The window shows only the conversation's first pending permission, so
  // the card is this review's only once the gateway puts it first.
  const shown = await reviewShown(stack, review)
  if (!shown) {
    failures.push("the window's approval is not the review the call opened")
    return seen
  }
  const card = await approvalShown(page, SERVER, DESTRUCTIVE)
  if (!card) {
    failures.push(`the window shows no approval naming ${DESTRUCTIVE}`)
    return seen
  }
  seen.card = (await card.innerText()).replace(/\s+/g, " ").trim()
  const label = offeredLabel(review.options, effect)
  failures.push(
    ...(await unofferedAnswers(card, review.options)).map((line) => `the card ${line}`),
  )
  if (!label) failures.push(`the review offers no ${effect}`)
  else if ((await card.getByRole("button", { name: label, exact: true }).count()) === 0)
    failures.push(`no "${label}" button on the card`)
  else await card.getByRole("button", { name: label, exact: true }).click()
  const gone = await reviewGone(stack, review, 10_000)
  if (!gone) failures.push(`the review is still pending after ${label ?? effect}`)
  return seen
}

/**
 * Signs the context in with the gateway's owner token (`signIn`), then loads
 * the window, which opens the newest session of its first channel by itself
 * (`usecases/updates.ts`): the stack's one conversation. With the page,
 * returns `reviewsBefore`, the app's reviews pending before the window
 * loaded, and `conversationOpen`, whether the window opened the
 * conversation (#485, B1″ and B5).
 */
async function openConversation(browser, stack, layout) {
  let reviewsBefore
  const opened = await openPage(browser, {
    url: `${stack.url}?gateway`,
    layout,
    // Before the window's page exists (`signIn`).
    beforeLoad: async (context) => {
      reviewsBefore = await signIn(context, stack)
    },
  })
  try {
    const conversationOpen = await windowOpened(opened.page, stack, reviewsBefore)
    await settled(opened.page)
    return { ...opened, reviewsBefore, conversationOpen }
  } catch (error) {
    // No step will report the page's lines, so the error carries them, and
    // the page is closed rather than left open until the browser closes.
    const lines = [
      ...opened.errors.splice(0),
      ...opened.harmless.splice(0).map((line) => `harmless: ${line}`),
    ]
    await opened.close().catch(() => {})
    if (lines.length > 0) error.message += `\n  the page's lines: ${lines.join("; ")}`
    throw error
  }
}

/**
 * Signs `context` in from a page of its own on the sample page, which it
 * closes: the window's page then records only its own lines. This script
 * reports them on each step's result, errors as failures and the rest as
 * `harmless`, and in the error when opening the conversation throws; lines
 * that arrive after the last step are not reported yet (#494). Returns the
 * app's reviews pending then: whatever a previous engine's page left, not
 * yet withdrawn, is not this page's (R4). Read before the window loads: it opens the conversation
 * on load, so the app can mount, and its first call open a review, at any
 * point after (#485).
 */
async function signIn(context, stack) {
  const page = await context.newPage()
  try {
    await page.goto(stack.url, { waitUntil: "domcontentloaded" })
    // The token goes to the page's own origin, which proxies it to the
    // gateway; it is never printed or kept.
    const status = await page.evaluate(
      async (token) =>
        (
          await fetch("/browser/login", {
            method: "POST",
            credentials: "same-origin",
            headers: { "Content-Type": "application/json", "X-Nessa-Browser": "1" },
            body: JSON.stringify({ token }),
          })
        ).status,
      stack.token(),
    )
    if (status < 200 || status > 299)
      throw new CannotRun(`the gateway refused the page's sign-in (${status})`)
    return await pendingReviews(stack)
  } finally {
    await page.close()
  }
}

/**
 * Waits up to `ms` for the window to have opened the conversation on load
 * (#485): its inline app live, and the app's first destructive call's review
 * in the gateway, a key not in `baseline` (B1″). Waiting for both fixes the
 * order, so the steps after begin from the same state each run.
 *
 * Returns false only when the window shows no app view of the conversation
 * (B5), which `renders` reports. An app that is drawn but not live is
 * `renders`' to report, and a review that never arrives (B6) is `allow`'s,
 * with B4's message.
 */
async function windowOpened(page, stack, baseline, ms = 20_000) {
  const until = Date.now() + ms
  const left = () => Math.max(until - Date.now(), 1)
  const framed = await page
    .waitForSelector(css.appFrameIn("inline"), { timeout: left(), state: "attached" })
    .then(() => true)
    .catch(() => false)
  if (!framed) return (await page.$(css.appView)) !== null
  const app = await appFrame(page, "inline", left()).then(
    (frame) => frame.app,
    () => null,
  )
  const live = await app
    ?.waitForSelector(css.reviewState("live"), { timeout: left() })
    .then(() => true)
    .catch(() => false)
  if (live) await reviewOpened(stack, baseline, left())
  return true
}

const checks = {
  renders: async (page, stack, shot, opened) => {
    const failures = []
    if (!opened.conversationOpen) {
      if (shot) await page.screenshot({ path: shot })
      failures.push("the window did not open the conversation (#485, B5)")
      return { failures }
    }
    // The app's frame is drawn once its resource is read and fetched: a
    // view that never gets there has failed, and says how in its lifecycle.
    const drawn = await page
      .waitForSelector(css.appFrameIn("inline"), { timeout: 30_000, state: "attached" })
      .then(() => true)
      .catch(() => false)
    if (!drawn) {
      const view = await page.evaluate((selector) => {
        const view = document.querySelector(selector)
        return { lifecycle: view?.getAttribute("data-app-view"), text: view?.textContent }
      }, css.appView)
      if (shot) await page.screenshot({ path: shot })
      failures.push(
        `the app is not drawn inline within 30 s: its view is ${view.lifecycle}, saying "${view.text}"`,
      )
      return { seen: { view }, failures }
    }
    const { proxy, app } = await appFrame(page, "inline", 30_000)
    await app
      .waitForSelector(css.reviewState("live"), { timeout: 20_000 })
      .catch(() => {})
    // The session has one review_rows call: it is one step of the
    // transcript, every inline frame is its mount, and only one may be, or a
    // later step's review may be another's.
    await settled(page)
    const cards = await page.locator(css.transcriptStep, { hasText: APP_TOOL }).count()
    const frames = (await page.$$(css.appFrameIn("inline"))).length
    const drawnOnce = [oneCard(cards), oneMount(frames)].filter(Boolean)
    if (drawnOnce.length > 0) {
      if (shot) await page.screenshot({ path: shot })
      failures.push(...drawnOnce)
      return { seen: { cards, frames }, failures }
    }
    const seen = await app.evaluate(() => ({
      state: document.body.getAttribute("data-review-state"),
      mode: document.body.getAttribute("data-review-mode"),
      heading: document.querySelector("h1")?.textContent ?? null,
      origin: self.origin,
      url: location.href,
    }))
    seen.cards = cards
    seen.frames = frames
    seen.result = await output(app, "result")
    const pageOrigin = new URL(page.url()).origin
    seen.proxyOrigin = new URL(proxy.url()).origin
    if (seen.state !== "live") failures.push(`the app is ${seen.state}, not live`)
    if (seen.mode !== "inline") failures.push(`the app is told ${seen.mode}, not inline`)
    if (seen.heading !== "Review rows (nessa-test)")
      failures.push(`the app's document is not the server's: ${seen.heading}`)
    if (seen.result !== '{"rows":[1,2]}')
      failures.push(`the app was told result ${seen.result}`)
    if (seen.proxyOrigin === pageOrigin)
      failures.push("the sandbox proxy is on the window's own origin")
    if (seen.origin !== "null")
      failures.push(`the app's origin is ${seen.origin}, not opaque`)
    return { seen, failures }
  },

  hidden: async (page) => {
    const failures = []
    const { app } = await appFrame(page, "inline")
    const want = `error: ${names.gatewayRefused.notForApp}`
    const seen = {
      noUi: await output(app, "hidden-no-ui"),
      withUi: await output(app, "hidden-with-ui"),
    }
    if (seen.withUi !== want)
      failures.push(
        `the hidden tool declaring a UI was answered "${seen.withUi}", not "${want}"`,
      )
    if (seen.noUi !== want)
      failures.push(
        `the hidden tool declaring no UI was answered "${seen.noUi}", not "${want}"`,
      )
    return { seen, failures }
  },

  allow: async (page, stack, shot, opened) => {
    const failures = []
    const { app } = await appFrame(page, "inline")
    const before = await said(app, "first")
    if (before !== "pending")
      failures.push(`the destructive call was answered before its review: "${before}"`)
    // The first call was made as the app mounted.
    const review = await reviewAndAnswer(
      page,
      stack,
      opened.reviewsBefore,
      "allow",
      failures,
      () => said(app, "first"),
    )
    const answer = await output(app, "first")
    if (answer !== "ok: Deleted row 2.")
      failures.push(`after Allow Once the app shows "${answer}"`)
    return { seen: { before, review, answer }, failures }
  },

  deny: async (page, stack) => {
    const failures = []
    const { app } = await appFrame(page, "inline")
    // A review left pending (the mount's own, when allow did not run) would
    // hold the window's card ahead of this step's.
    const baseline = await settleEarlier(page, stack, failures)
    await app.click(css.reviewControl("delete"))
    const before = await said(app, "again")
    if (before !== "pending")
      failures.push(
        `the second destructive call was answered before its review: "${before}"`,
      )
    const review = await reviewAndAnswer(
      page,
      stack,
      baseline,
      "deny",
      failures,
      () => said(app, "again"),
    )
    const answer = await output(app, "again")
    if (answer !== `error: ${names.gatewayRefused.declined}`)
      failures.push(`after Deny the app shows "${answer}"`)
    return { seen: { before, review, answer }, failures }
  },

  release: async (page, stack) => {
    const failures = []
    const inline = await appFrame(page, "inline")
    const panes = await paneCount(page)
    await inline.app.click(css.reviewControl("fullscreen"))
    await paneCountIs(page, panes + 1)
    const pane = await appFrame(page, "pane", 20_000)
    await pane.app
      .waitForSelector(css.reviewState("live"), { timeout: 20_000 })
      .catch(() => {})
    const paneMode = await pane.app.evaluate(() =>
      document.body.getAttribute("data-review-mode"),
    )
    if (paneMode !== "fullscreen") failures.push(`the pane's app is told ${paneMode}`)
    // The pane's own mount: its tool result arrives, and it makes no calls of its own.
    const baseline = await settleEarlier(page, stack, failures)
    // A pointer click Playwright accepts can miss this button in the sandboxed
    // pane: the output stays empty and the gateway records no call. The
    // document click runs the same listener. Which one made the call is
    // `paneClick`.
    await pane.app.click(css.reviewControl("delete"), { timeout: 3_000 }).catch(() => {})
    let paneClick = "pointer"
    if ((await said(pane.app, "again")) === "") {
      paneClick = "document"
      await pane.app.locator(css.reviewControl("delete")).evaluate((button) => {
        button.click()
      })
    }
    const waited = await awaitReview(stack, baseline, () => said(pane.app, "again"))
    if (waited.kind !== "review") {
      failures.push(
        waited.kind === "answered"
          ? `the pane app's call was answered without a review: "${waited.output}"`
          : `the pane app's destructive call reached no review; ${reviewAbsentMessage(waited.samples, waited.reads)}`,
      )
      return { seen: { paneMode, paneClick }, failures }
    }
    const waiting = waited.review
    if (!(await reviewShown(stack, waiting)))
      failures.push("the window's approval is not the review the pane's call opened")
    const card = await approvalShown(page, SERVER, DESTRUCTIVE)
    if (!card) failures.push(`the window shows no approval naming ${DESTRUCTIVE}`)
    const paneSaid = await said(pane.app, "again")
    if (paneSaid !== "pending")
      failures.push(`the third call was answered before the pane closed: "${paneSaid}"`)
    // Close the pane: the place is removed (L24), so its mount is released.
    const paneLocator = page.locator(css.widgetPane).first()
    await paneLocator.hover()
    await paneLocator.getByRole("button", { name: names.closePane }).first().click()
    const closedAt = Date.now()
    await until(
      page,
      (frame) => !document.querySelector(frame),
      css.appFrameIn("pane"),
      5000,
    )
    if (await page.$(css.appFrameIn("pane")))
      failures.push("the pane's app frame is still on the page after its close")
    const withdrawn = await reviewGone(stack, waiting, 15_000)
    const withdrawnAt = Date.now()
    const withdrawnMs = withdrawn ? withdrawnAt - closedAt : null
    if (!withdrawn) failures.push("the review was not withdrawn when the pane closed")
    const cardGone = await approvalGone(page, SERVER, DESTRUCTIVE, 5000)
    // From the withdrawal seen to the card gone; null when either was not seen.
    const cardGoneAfterWithdrawnMs =
      withdrawn && cardGone ? Date.now() - withdrawnAt : null
    if (!cardGone)
      failures.push("the window still shows the review after the pane closed")
    // The inline mount is another: untouched.
    const inlineState = await inline.app.evaluate(() =>
      document.body.getAttribute("data-review-state"),
    )
    if (inlineState !== "live") failures.push(`the inline app is ${inlineState} after`)
    return {
      seen: {
        paneMode,
        paneClick,
        review: { origin: waiting.origin, toolName: waiting.toolName },
        paneSaid,
        withdrawn: Boolean(withdrawn),
        withdrawnMs,
        cardGone,
        cardGoneAfterWithdrawnMs,
        inlineState,
      },
      failures,
    }
  },
}

await main(
  meta,
  async ({ options, rep, target: stack }) => {
    const only = chosen(options.only, steps, options.list)
    rep.add({
      name: "setup",
      seen: { title: stack.title },
      timings: stack.timings,
      failures: [],
    })
    if (options.shots) mkdirSync(options.shots, { recursive: true })
    await withEngines(options, rep, async (engine, browser) => {
      for (const layout of options.layouts) {
        const started = Date.now()
        let opened
        try {
          opened = await openConversation(browser, stack, layout)
        } catch (error) {
          rep.add({
            name: "open",
            engine,
            layout,
            cannotRun: error instanceof CannotRun,
            error: error.message.split("\n")[0],
            detail: error.message,
          })
          continue
        }
        let stopped = null
        try {
          for (const name of only) {
            if (stopped) {
              rep.add({
                name,
                engine,
                layout,
                cannotRun: true,
                error: `not run: ${stopped} failed`,
              })
              continue
            }
            const at = Date.now()
            let result
            try {
              result = await checks[name](
                opened.page,
                stack,
                options.shots &&
                  join(options.shots, `mcp-apps-gateway-${engine}-${layout}-${name}.png`),
                opened,
              )
            } catch (error) {
              result = { failures: [], error: error.message.split("\n")[0] }
            }
            const entry = rep.add({
              name,
              engine,
              layout,
              ms: Date.now() - at,
              ...result,
              failures: [...(result.failures ?? []), ...opened.errors.splice(0)],
              harmless: opened.harmless.splice(0),
            })
            // A refused call leaves nothing waiting, so the steps after
            // `hidden` begin from the same page whatever it saw.
            if (!entry.ok && !independent.has(name)) stopped = name
          }
          if (options.shots) {
            await opened.page.screenshot({
              path: join(options.shots, `mcp-apps-gateway-${engine}-${layout}.png`),
            })
          }
        } finally {
          await opened.close()
          log(`${engine} ${layout}: ${Date.now() - started} ms`)
        }
      }
    })
  },
  startStack,
)
