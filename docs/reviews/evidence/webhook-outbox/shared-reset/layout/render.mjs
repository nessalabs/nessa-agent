import { chromium } from '/tmp/nessa-docs/node_modules/playwright/index.mjs';
import { writeFileSync } from 'node:fs';
const browser=await chromium.launch({executablePath:'/usr/bin/chromium', headless:true});
const page=await browser.newPage({viewport:{width:1500,height:1000}});
const errors=[];
page.on('pageerror', e=>errors.push(String(e)));
await page.goto('http://127.0.0.1:4311/docs/gateway-webhook-outbox');
await page.waitForSelector('.document-layout[data-doc-id="gateway-webhook-outbox"]');
await page.waitForFunction(()=>document.querySelectorAll('figure.diagram').length===2 && [...document.querySelectorAll('figure.diagram')].every(f=>f.dataset.state!=='rendering'));
await page.evaluate(()=>document.fonts.ready);
for(let i=0;i<2;i++)await page.locator('figure.diagram').nth(i).getByRole('button',{name:'Fit',exact:true}).click();
const served=await (await page.request.get('http://127.0.0.1:4311/api/documents/gateway-webhook-outbox')).json();
if(served.document.sourceRevision!=='b3dc0d4688e473fa40bbbeddf00bb9f510130bf1')throw new Error('source checkpoint mismatch');
const diagrams=await page.locator('figure.diagram').evaluateAll(figures=>figures.map(f=>({state:f.dataset.state,svgs:f.querySelectorAll('svg').length,rect:{width:f.getBoundingClientRect().width,height:f.getBoundingClientRect().height},text:f.textContent.slice(0,120)})));
for(let i=0;i<diagrams.length;i++)await page.locator('figure.diagram').nth(i).screenshot({path:`/workspace/nessa-agent/docs/reviews/evidence/webhook-outbox/shared-reset/layout/diagram-${i+1}.png`});
const result={page:'gateway-webhook-outbox',rendererRevision:'c0bc0627611b100ab71a96cc6fe2fb65f1a014d8',sourceRevision:served.document.sourceRevision,browser:await browser.version(),diagrams,pageErrors:errors};
writeFileSync('/workspace/nessa-agent/docs/reviews/evidence/webhook-outbox/shared-reset/layout/render.json',JSON.stringify(result,null,2)+'\n');
console.log(JSON.stringify(result));
await browser.close();
if(errors.length||diagrams.some(d=>d.state==='error'||d.svgs<1))process.exitCode=1;
